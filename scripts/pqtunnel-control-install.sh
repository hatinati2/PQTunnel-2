#!/usr/bin/env bash
set -Eeuo pipefail
umask 077

REPO="hatinati2/PQTunnel-2"
REF=""
ROLE=""
PANEL_DOMAIN=""
PANEL_PORT="6100"
CONTROL_URL=""
PAIR_TOKEN=""
WORK=""

fail() { printf 'PQTunnel control installer: %s\n' "$*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || fail "required command is missing: $1"; }
cleanup() { [[ -z "$WORK" ]] || rm -rf -- "$WORK"; }
trap cleanup EXIT

usage() {
  cat <<'USAGE'
One-line PQTunnel control-plane installer. Run once on each host.

Gateway:
  curl -fsSL https://raw.githubusercontent.com/hatinati2/PQTunnel-2/COMMIT_SHA/scripts/pqtunnel-control-install.sh | sudo bash -s -- --ref COMMIT_SHA --role gateway --panel-domain control.example.com --panel-port 6100

Dialer (generated by the Gateway web panel):
  curl -fsSL https://raw.githubusercontent.com/hatinati2/PQTunnel-2/COMMIT_SHA/scripts/pqtunnel-control-install.sh | sudo bash -s -- --ref COMMIT_SHA --role dialer --control-url 'https://control.example.com:6100/SECRET_PATH' --pair-token ONE_TIME_TOKEN

The installer downloads and builds the exact reviewed commit. It installs the manager
and standalone endpoint setup worker. On the Dialer it also enrolls and starts the
fleet agent. Tunnel services remain stopped until explicitly started in the web panel.
USAGE
}

while (($#)); do
  case "$1" in
    --ref) [[ $# -ge 2 ]] || fail 'missing --ref'; REF="$2"; shift 2 ;;
    --role) [[ $# -ge 2 ]] || fail 'missing --role'; ROLE="$2"; shift 2 ;;
    --panel-domain) [[ $# -ge 2 ]] || fail 'missing --panel-domain'; PANEL_DOMAIN="$2"; shift 2 ;;
    --panel-port) [[ $# -ge 2 ]] || fail 'missing --panel-port'; PANEL_PORT="$2"; shift 2 ;;
    --control-url) [[ $# -ge 2 ]] || fail 'missing --control-url'; CONTROL_URL="$2"; shift 2 ;;
    --pair-token) [[ $# -ge 2 ]] || fail 'missing --pair-token'; PAIR_TOKEN="$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; fail "unknown option: $1" ;;
  esac
done

[[ "$EUID" -eq 0 ]] || fail 'run this one-line installer with sudo/root.'
[[ "$REF" =~ ^[0-9a-f]{40}$ ]] || fail '--ref must be a reviewed lowercase 40-character commit SHA; mutable branch names are refused.'
[[ "$ROLE" == gateway || "$ROLE" == dialer ]] || fail '--role must be gateway or dialer.'
[[ "$(uname -s)" == Linux ]] || fail 'Linux is the only supported server platform.'
[[ -d /run/systemd/system ]] || fail 'systemd is required.'
for cmd in curl tar python3 install chmod stat awk grep sed sha256sum; do need "$cmd"; done

case "$ROLE" in
  gateway)
    [[ -n "$PANEL_DOMAIN" ]] || fail 'Gateway install requires --panel-domain with a DNS name pointing to this Gateway.'
    [[ "$PANEL_PORT" =~ ^[0-9]{1,5}$ ]] || fail '--panel-port must be an integer from 1 to 65535.'
    (( 10#$PANEL_PORT >= 1 && 10#$PANEL_PORT <= 65535 )) || fail '--panel-port must be between 1 and 65535.'
    python3 - "$PANEL_DOMAIN" <<'PY'
import re, sys
if not re.fullmatch(r"(?=.{1,253}$)(?:[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?\.)+[A-Za-z]{2,63}", sys.argv[1]):
    raise SystemExit("panel domain must be a fully qualified ASCII DNS name")
PY
    [[ -z "$CONTROL_URL$PAIR_TOKEN" ]] || fail 'do not supply Dialer enrollment arguments to a Gateway install.'
    ;;
  dialer)
    [[ -n "$CONTROL_URL" && -n "$PAIR_TOKEN" ]] || fail 'Dialer install requires --control-url and --pair-token from the Gateway panel.'
    [[ "$CONTROL_URL" == https://* ]] || fail '--control-url must use HTTPS; plaintext HTTP enrollment is refused.'
    [[ "$PAIR_TOKEN" =~ ^[0-9a-f]{64}$ ]] || fail '--pair-token must be a 64-character one-time hexadecimal token.'
    [[ -z "$PANEL_DOMAIN" ]] || fail '--panel-domain is used only on the Gateway.'
    ;;
esac

case "$(uname -m)" in
  x86_64|amd64) GO_ARCH=amd64 ;;
  aarch64|arm64) GO_ARCH=arm64 ;;
  *) fail "unsupported Linux build architecture: $(uname -m)" ;;
esac

. /etc/os-release
[[ "${ID:-}" == ubuntu || "${ID:-}" == debian ]] || fail 'automatic prerequisite setup supports Ubuntu/Debian only.'
if ! command -v apt-get >/dev/null 2>&1; then fail 'apt-get is required to install missing base prerequisites.'; fi
missing=()
for pair in 'curl:curl' 'tar:tar' 'python3:python3' 'sha256sum:coreutils'; do
  command -v "${pair%%:*}" >/dev/null 2>&1 || missing+=("${pair#*:}")
done
if (("${#missing[@]}")); then
  apt-get update
  DEBIAN_FRONTEND=noninteractive apt-get install -y ca-certificates "${missing[@]}"
fi

go_is_sufficient() {
  local value
  command -v go >/dev/null 2>&1 || return 1
  value="$(go env GOVERSION 2>/dev/null | sed 's/^go//')" || return 1
  awk -v v="$value" 'BEGIN { split(v,a,"."); exit !((a[1]+0)>1 || ((a[1]+0)==1 && (a[2]+0)>=27)) }'
}

if ! go_is_sufficient; then
  case "$(uname -m)" in
    x86_64|amd64) GO_ARCH=amd64 ;;
    aarch64|arm64) GO_ARCH=arm64 ;;
    *) fail "unsupported build architecture: $(uname -m)" ;;
  esac
  WORK="$(mktemp -d -t pqtunnel-control-install.XXXXXX)"
  chmod 0700 "$WORK"
  curl --fail --silent --show-error --location 'https://go.dev/dl/?mode=json' -o "$WORK/go-versions.json"
  read -r GO_VERSION GO_FILE GO_SHA < <(python3 - "$GO_ARCH" "$WORK/go-versions.json" <<'PY'
import json, re, sys
arch, filename = sys.argv[1], sys.argv[2]
with open(filename, encoding="utf-8") as stream:
    releases = json.load(stream)
for release in releases:
    version = release.get("version", "")
    match = re.fullmatch(r"go(\d+)\.(\d+)\.(\d+)", version)
    if not match:
        continue
    major, minor = int(match.group(1)), int(match.group(2))
    if not (major > 1 or (major == 1 and minor >= 27)):
        continue
    for item in release.get("files", []):
        if item.get("os") == "linux" and item.get("arch") == arch and item.get("kind") == "archive" and item.get("filename", "").endswith(".tar.gz"):
            print(version, item["filename"], item["sha256"])
            raise SystemExit(0)
raise SystemExit("no Go >= 1.27 Linux archive found in official download metadata")
PY
  ) || fail 'could not select a supported Go toolchain from official metadata.'
  GO_HOME="/opt/pqtunnel-go-$GO_VERSION"
  if [[ ! -x "$GO_HOME/bin/go" ]]; then
    [[ ! -e "$GO_HOME" ]] || fail "$GO_HOME already exists but is not a usable Go installation; inspect it manually."
    curl --fail --silent --show-error --location "https://go.dev/dl/$GO_FILE" -o "$WORK/$GO_FILE"
    printf '%s  %s\n' "$GO_SHA" "$WORK/$GO_FILE" | sha256sum --check --status || fail 'Go toolchain checksum verification failed.'
    install -d -o root -g root -m 0755 "$GO_HOME"
    tar -xzf "$WORK/$GO_FILE" --strip-components=1 -C "$GO_HOME"
    chown -R root:root "$GO_HOME"
  fi
  export PATH="$GO_HOME/bin:$PATH"
fi
go_is_sufficient || fail 'Go 1.27 or later is required; toolchain verification did not pass.'

WORK="${WORK:-$(mktemp -d -t pqtunnel-control-install.XXXXXX)}"
chmod 0700 "$WORK"
mkdir -p "$WORK/source"
curl --fail --silent --show-error --location \
  -H 'Accept: application/vnd.github+json' \
  "https://api.github.com/repos/$REPO/tarball/$REF" -o "$WORK/source.tar.gz"
tar -xzf "$WORK/source.tar.gz" --strip-components=1 -C "$WORK/source"
SOURCE="$WORK/source"
grep -Fxq 'module github.com/hatinati2/PQTunnel-2' "$SOURCE/go.mod" || fail 'downloaded source does not match the expected repository.'
[[ -f "$SOURCE/scripts/build-release-bundles.sh" && -f "$SOURCE/scripts/install-manager.sh" && -x "$SOURCE/scripts/pqtunnel-node-setup-worker.py" ]] || fail 'the pinned commit lacks manager/endpoint build assets.'
VERSION="$(sed -nE 's/^VERSION="(v[0-9A-Za-z._-]+)"$/\1/p' "$SOURCE/install.sh" | head -n1)"
[[ "$VERSION" =~ ^v[0-9A-Za-z._-]+$ ]] || fail 'could not determine the pinned source bundle version.'

export PATH
export GOTOOLCHAIN=local
export CGO_ENABLED=0

# Build the exact pinned source into the same verified Linux bundle format used
# by CI. install-manager then installs prebuilt binaries without requiring Go
# or mutable source branches on the destination host.
DIST="$WORK/dist"
bash "$SOURCE/scripts/build-release-bundles.sh" "$VERSION" "$DIST"
BUNDLE="$WORK/PQTunnel-$VERSION-linux-$GO_ARCH"
tar -xzf "$DIST/PQTunnel-$VERSION-linux-$GO_ARCH.tar.gz" -C "$WORK"
[[ -x "$BUNDLE/pqtunnel-manager" && -x "$BUNDLE/pqtunnel-agent" && -x "$BUNDLE/pqtunnel-pki" ]] || fail 'the pinned Linux bundle is missing a required management binary.'

if [[ "$ROLE" == gateway ]]; then
  command -v certbot >/dev/null 2>&1 || {
    apt-get update
    DEBIAN_FRONTEND=noninteractive apt-get install -y certbot
  }
  python3 - <<'PY'
import socket
sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
try:
    sock.bind(("0.0.0.0", 80))
except OSError as exc:
    raise SystemExit(f"TCP/80 is not available for the ACME HTTP-01 challenge: {exc}")
finally:
    sock.close()
PY
  certbot certonly --standalone --preferred-challenges http --non-interactive --agree-tos \
    --register-unsafely-without-email --keep-until-expiring -d "$PANEL_DOMAIN"
  CERT_DIR="/etc/letsencrypt/live/$PANEL_DOMAIN"
  [[ -s "$CERT_DIR/fullchain.pem" && -s "$CERT_DIR/privkey.pem" ]] || fail 'Certbot did not create the expected TLS certificate files.'
  install -d -o root -g root -m 0755 /etc/letsencrypt/renewal-hooks/deploy
  cat > /etc/letsencrypt/renewal-hooks/deploy/50-pqtunnel-manager.sh <<'HOOK'
#!/usr/bin/env bash
set -Eeuo pipefail
systemctl try-restart pqtunnel-manager.service
HOOK
  chmod 0750 /etc/letsencrypt/renewal-hooks/deploy/50-pqtunnel-manager.sh
  systemctl enable --now certbot.timer
  export PQTUNNEL_MANAGER_INSTALL_REF="$REF"
  bash "$BUNDLE/scripts/install-manager.sh" \
    --source "$BUNDLE" --role gateway --with-node-endpoint \
    --public-tls --public-host "$PANEL_DOMAIN" --tls-cert "$CERT_DIR/fullchain.pem" \
    --tls-key "$CERT_DIR/privkey.pem" --panel-port "$PANEL_PORT"
  printf '\nGateway Control Plane installation finished.\n'
  printf 'Open the HTTPS panel URL printed above from your phone.\n'
  printf 'Provider firewall: allow TCP/80 for ACME renewal and TCP/%s for the HTTPS panel.\n' "$PANEL_PORT"
else
  bash "$BUNDLE/scripts/install-manager.sh" --source "$BUNDLE" --role dialer --with-node-endpoint
  /usr/local/sbin/pqtunnel-agent --enroll \
    --control-url "$CONTROL_URL" --pair-token "$PAIR_TOKEN" \
    --config /var/lib/pqtunnel-agent/agent.json
  chmod 0600 /var/lib/pqtunnel-agent/agent.json
  systemctl daemon-reload
  systemctl enable --now pqtunnel-agent
  systemctl --no-pager --full status pqtunnel-agent
  printf '\nDialer Agent enrolled and running. The tunnel endpoint remains stopped until started in the Gateway web panel.\n'
fi
