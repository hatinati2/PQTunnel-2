type agentConfig struct {
	BaseURL string `json:"base_url"`
	NodeID  string `json:"node_id"`
	Name    string `json:"name"`
	Key     string `json:"key"`
}

func main() {
	var (
		enroll    = flag.Bool("enroll", false, "enroll this Dialer with a one-use Gateway invite")
		controlURL = flag.String("control-url", "", "Gateway panel base URL, including its secret path")
		pairToken = flag.String("pair-token", "", "one-time enrollment token generated by the Gateway panel")
		configPath = flag.String("config", envOr("PQTUNNEL_AGENT_CONFIG", "/etc/pqtunnel-agent/agent.json"), "protected agent credential file")
	)
	flag.Parse()

	if *enroll {
		if *controlURL == "" || *pairToken == "" {
			fatal(errors.New("--enroll requires --control-url and --pair-token"))
		}
		if err := enrollAgent(*controlURL, *pairToken, *configPath); err != nil {
			fatal(err)
		}
		fmt.Println("PQTunnel Dialer agent enrolled. Credentials saved with mode 0600.")
		return
	}

	cfg, err := readConfig(*configPath)
	if err != nil {
		fatal(err)
	}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	if err := run(ctx, cfg); err != nil && !errors.Is(err, context.Canceled) {
		fatal(err)
	}
}

func enrollAgent(controlURL, token, configPath string) error {
	base, err := validateBaseURL(controlURL)
	if err != nil {
		return err
	}
	if len(token) != 64 {
		return errors.New("pair token must be exactly 64 hexadecimal characters")
	}
	if _, err := hex.DecodeString(token); err != nil {
		return errors.New("pair token must be hexadecimal")
	}

	curve := ecdh.X25519()
	privateKey, err := curve.GenerateKey(rand.Reader)
	if err != nil {
		return errors.New("could not generate agent enrollment key")
	}
	nodeID, err := randomID()
	if err != nil {
		return err
	}
	name, _ := os.Hostname()
	name = sanitizeName(name)
	if name == "" {
		name = "dialer"
	}
	request := fleet.EnrollRequest{
		Token: token, NodeID: nodeID, Name: name, Role: "dialer",
		PublicKey: base64.RawURLEncoding.EncodeToString(privateKey.PublicKey().Bytes()),
	}
	body, err := json.Marshal(request)
	if err != nil {
		return err
	}
	client := &http.Client{
		Timeout: 20 * time.Second,
		CheckRedirect: func(_ *http.Request, _ []*http.Request) error { return http.ErrUseLastResponse },
	}
	response, err := client.Post(base+"/agent/enroll", "application/json", bytes.NewReader(body))
	if err != nil {
		return fmt.Errorf("Gateway enrollment endpoint is unreachable: %w", err)
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		_, _ = io.Copy(io.Discard, io.LimitReader(response.Body, 2048))
		return fmt.Errorf("Gateway rejected the enrollment request (HTTP %d); create a fresh invite in the panel", response.StatusCode)
	}
	var reply fleet.EnrollResponse
	if err := fleet.ReadJSONBody(response.Body, 16<<10, &reply); err != nil {
		return fmt.Errorf("Gateway enrollment response is invalid: %w", err)
	}
	credentials, err := fleetCompleteEnrollment(token, privateKey, reply)
	if err != nil {
		return fmt.Errorf("could not verify Gateway enrollment response: %w", err)
	}
	key, err := hex.DecodeString(credentials.Key)
	if err != nil || len(key) != 32 || credentials.NodeID != nodeID {
		return errors.New("Gateway returned invalid enrollment credentials")
	}
	cfg := agentConfig{BaseURL: base, NodeID: nodeID, Name: name, Key: credentials.Key}
	return writeConfig(configPath, cfg)
}

func fleetCompleteEnrollment(token string, privateKey *ecdh.PrivateKey, reply fleet.EnrollResponse) (fleet.Credentials, error) {
	// The function intentionally lives here so the agent's X25519 private key
	// never leaves this process or the local machine.
	return fleet.CompleteEnrollmentForAgent(token, privateKey, reply)
}

func validateBaseURL(value string) (string, error) {
	u, err := url.Parse(strings.TrimSpace(value))
	if err != nil || u.Scheme != "https" || u.Host == "" || u.User != nil || u.RawQuery != "" ||
		u.Fragment != "" || u.RawPath != "" || !validSecretPath(u.Path) {
		return "", errors.New("control URL must use HTTPS and include the 256-bit Gateway secret path")
	}
	return strings.TrimRight(u.String(), "/"), nil
}

func validSecretPath(path string) bool {
	if len(path) != 65 || path[0] != '/' { return false }
	for _, c := range path[1:] {
		if !((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f')) { return false }
	}
	return true
}

func randomID() (string, error) {
	value := make([]byte, 16)
	if _, err := rand.Read(value); err != nil {
		return "", err
	}
	return hex.EncodeToString(value), nil
}

func sanitizeName(value string) string {
	var out strings.Builder
	for _, c := range value {
		if (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '-' || c == '_' || c == '.' {
			out.WriteRune(c)
		}
	}
	if out.Len() > 48 {
		return out.String()[:48]
	}
	return out.String()
}

func writeConfig(path string, cfg agentConfig) error {
	if !filepath.IsAbs(path) || cfg.NodeID == "" || len(cfg.Key) != 64 {
		return errors.New("agent config path or credentials are invalid")
	}
	key, err := hex.DecodeString(cfg.Key)
	if err != nil || len(key) != 32 {
		return errors.New("agent encryption key is invalid")
	}
	data, err := json.MarshalIndent(cfg, "", "  ")
	if err != nil {
		return err
	}
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0700); err != nil {
		return err
	}
	if err := os.Chmod(dir, 0700); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, ".agent-config-*")
	if err != nil {
		return err
	}
	name := tmp.Name()
	ok := false
	defer func() {
		_ = tmp.Close()
		if !ok {
			_ = os.Remove(name)
		}
	}()
	if err := tmp.Chmod(0600); err != nil {
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		return err
	}
	if err := tmp.Sync(); err != nil {
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Rename(name, path); err != nil {
		return err
	}
	ok = true
	return nil
}

func readConfig(path string) (agentConfig, error) {
	var cfg agentConfig
	if !filepath.IsAbs(path) {
		return cfg, errors.New("agent config path must be absolute")
	}
	info, err := os.Lstat(path)
	if err != nil {
		return cfg, fmt.Errorf("agent is not enrolled; install it using the one-time command from the Gateway panel: %w", err)
	}
	if !info.Mode().IsRegular() || info.Mode()&os.ModeSymlink != 0 || info.Mode().Perm()&0077 != 0 {
		return cfg, errors.New("agent config must be a regular file with permissions 0600 or stricter")
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return cfg, err
	}
	if err := json.Unmarshal(data, &cfg); err != nil {
		return cfg, errors.New("agent config file is invalid")
	}
	if _, err := validateBaseURL(cfg.BaseURL); err != nil || cfg.NodeID == "" {
		return cfg, errors.New("agent config is missing a valid Gateway URL or node identity")
	}
	key, err := hex.DecodeString(cfg.Key)
	if err != nil || len(key) != 32 {
		return cfg, errors.New("agent config has an invalid encryption key")
	}
	return cfg, nil
}

func run(ctx context.Context, cfg agentConfig) error {
	key, err := hex.DecodeString(cfg.Key)
	if err != nil || len(key) != 32 {
		return errors.New("agent encryption key is invalid")
	}
	controller, err := manager.New(manager.Options{
		Role: manager.RoleDialer,
		IPCSocket: "/run/pqtunnel/client-control.sock",
		EndpointMode: "transport",
	})
	if err != nil {
		return err
	}
	client := &http.Client{
		Timeout: 25 * time.Second,
		CheckRedirect: func(_ *http.Request, _ []*http.Request) error { return http.ErrUseLastResponse },
	}
	var lastResult *fleet.CommandResult
	lastCommandID := ""
	backoff := 2 * time.Second
	for {
		if err := ctx.Err(); err != nil {
			return err
		}
		snapshot := controller.ManagementSnapshot()
		request := fleet.AgentRequest{
			Sequence: time.Now().UnixNano(),
			Timestamp: time.Now().Unix(),
			Snapshot: snapshot,
			Result: lastResult,
		}
		envelope, err := fleet.SealForAgent(key, cfg.NodeID, request)
		if err != nil {
			return err
		}
		payload, _ := json.Marshal(envelope)
		req, err := http.NewRequestWithContext(ctx, http.MethodPost, cfg.BaseURL+"/agent/poll", bytes.NewReader(payload))
		if err != nil {
			return err
		}
		req.Header.Set("Content-Type", "application/json")
		req.Header.Set("Cache-Control", "no-store")
		response, err := client.Do(req)
		if err != nil {
			if !sleep(ctx, backoff) { return ctx.Err() }
			if backoff < 20*time.Second { backoff += 2*time.Second }
			continue
		}
		var reply fleet.Envelope
		parseErr := fleet.ReadJSONBody(response.Body, 2<<20, &reply)
		_ = response.Body.Close()
		if response.StatusCode != http.StatusOK || parseErr != nil {
			if !sleep(ctx, backoff) { return ctx.Err() }
			if backoff < 20*time.Second { backoff += 2*time.Second }
			continue
		}
		var answer fleet.AgentResponse
		if err := fleet.OpenForAgent(key, reply, &answer); err != nil {
			if !sleep(ctx, backoff) { return ctx.Err() }
			continue
		}
		backoff = 2 * time.Second
		if answer.AckID != "" && lastResult != nil && answer.AckID == lastResult.ID {
			lastResult = nil
			lastCommandID = ""
		}
		if answer.Command != nil && answer.Command.ID != "" && answer.Command.ID != lastCommandID {
			commandCtx, cancel := context.WithTimeout(ctx, 2*time.Minute)
			result := fleet.ExecuteLocal(commandCtx, controller, *answer.Command)
			cancel()
			lastCommandID = answer.Command.ID
			lastResult = &result
		}
		if !sleep(ctx, 2*time.Second) {
			return ctx.Err()
		}
	}
}

func sleep(ctx context.Context, duration time.Duration) bool {
	timer := time.NewTimer(duration)
	defer timer.Stop()
	select {
	case <-ctx.Done():
		return false
	case <-timer.C:
		return true
	}
}

func envOr(name, fallback string) string {
	if value := os.Getenv(name); value != "" {
		return value
	}
	return fallback
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "pqtunnel-agent:", err)
	os.Exit(1)
}

